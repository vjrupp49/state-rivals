"""Which layer drives the uncertainty in the ranking? (M4: variance decomposition.)

Re-runs the robustness Monte Carlo with ONE noise source at a time (all others fixed at baseline) and
reports, for the baseline top-30 pairs, the mean relative spread of M (sd/mean), the probability that the
baseline #1 stays #1, and the mean rank spread. It also runs the full combination for reference. Noise
magnitudes are the same analyst-chosen values as robustness.py (milestone M4 replaces them with
data-derived values), so this shows which layer the *current* assumptions make most influential.

Writes data/model/variance_decomposition.csv and docs/VARIANCE_DECOMPOSITION.md.

    python scripts/variance_decomposition.py [draws]
"""
import csv
import pathlib
import sys

import numpy as np

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import lib_model as LM  # noqa: E402
import robustness as RB  # noqa: E402

ROOT = LM.ROOT
MODEL = LM.MODEL
COMPONENTS = ["A (team attention)", "W (sport mix)", "S (salience, incl. per-sport)", "T (temperature)", "E (identity)", "all combined"]


def main(n_mc=150, seed=11):
    states, ids, A, _ = LM.load_A()
    n, I = A.shape
    reg = {e["entity_id"]: e for e in LM.load_entities()}
    ents = [reg[e] for e in ids]
    FAMS = RB.FAMS
    fam = np.array([FAMS.index(LM.fam_of(e)) for e in ids])
    E, buckets = LM.build_E(ents, states)
    edges = [e for e in LM.build_edges() if e[0] != "UNRESOLVED"]
    R0 = LM.build_R(ids, edges)
    M0, _ = RB.Mvec(A, R0, E, states)
    iu = np.triu_indices(n, 1)
    names = [(states[a], states[b]) for a, b in zip(*iu)]
    order0 = np.argsort(-M0)
    top = order0[:30]
    sidx = {s: k for k, s in enumerate(states)}
    sd = np.zeros((n, I))
    idx = {e: k for k, e in enumerate(ids)}
    with open(MODEL / "A_meta.csv", newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            sd[sidx[r["state_id"]], idx[r["entity_id"]]] = float(r["logsd"])
    F = np.zeros((I, len(FAMS)))
    F[np.arange(I), fam] = 1
    tgt = A @ F
    ei = np.array([ids.index(e[0]) for e in edges]); ej = np.array([ids.index(e[1]) for e in edges])
    ef = np.array([FAMS.index(e[2]) for e in edges]); es = np.array([e[4] for e in edges]); et = np.array([e[5] for e in edges])
    rng = np.random.default_rng(seed)
    NZ = RB.load_noise()
    RB.PLACE = LM.place_matrix(states, ids, ents)

    def draw(on):
        Ad = A * np.exp(sd * rng.standard_normal((n, I)) - 0.5 * sd ** 2) if "A" in on else A.copy()
        if "W" in on:
            fs = Ad @ F
            wn = np.exp(NZ["w_mix_sd"] * rng.standard_normal(tgt.shape) - 0.5 * NZ["w_mix_sd"] ** 2)
            t = tgt * wn
            ts = t.sum(1, keepdims=True)
            t = t * np.divide(tgt.sum(1, keepdims=True), ts, out=np.ones_like(ts), where=ts > 0)
            sc = np.divide(t, fs, out=np.ones_like(fs), where=fs > 0)
            Ad = Ad * (sc @ F.T)
        fm = np.exp(NZ["sport_mult_sd"] * rng.standard_normal(len(FAMS)) - 0.5 * NZ["sport_mult_sd"] ** 2) if "S" in on else np.ones(len(FAMS))
        S = np.zeros((I, I))
        S[ei, ej] = es * fm[ef] * (np.exp(NZ["s_edge_sd"] * rng.standard_normal(len(es)) - 0.5 * NZ["s_edge_sd"] ** 2) if "S" in on else 1.0)
        T = np.zeros((I, I))
        T[ei, ej] = np.minimum(1.0, et * (np.exp(NZ["t_sd"] * rng.standard_normal(len(et)) - 0.5 * NZ["t_sd"] ** 2) if "T" in on else 1.0))
        S *= np.minimum(1.0, LM.ROW_CAP / np.maximum(S.sum(1), 1e-12))[:, None]
        Ed = E
        if "E" in on:
            Ed = E * np.exp(NZ["e_sd"] * rng.standard_normal(E.shape) * (E > 0))
            Ed = Ed / Ed.sum(1, keepdims=True)
        return RB.Mvec(Ad, S * T, Ed, states)[0]

    plans = [("A (team attention)", {"A"}), ("W (sport mix)", {"W"}), ("S (salience, incl. per-sport)", {"S"}),
             ("T (temperature)", {"T"}), ("E (identity)", {"E"}), ("all combined", {"A", "W", "S", "T", "E"})]
    rows = []
    for label, on in plans:
        allM = np.array([draw(on) for _ in range(n_mc)])
        cv = allM[:, top].std(0) / np.maximum(allM[:, top].mean(0), 1e-12)
        ranks = np.argsort(np.argsort(-allM, axis=1), axis=1) + 1
        rows.append({"component": label, "mean_cv_top30": round(float(cv.mean()), 4),
                     "p_baseline_top1_stays_top1": round(float((ranks[:, order0[0]] == 1).mean()), 3),
                     "mean_rank_sd_top30": round(float(ranks[:, top].std(0).mean()), 2), "draws": n_mc})
        print(rows[-1])
    with open(MODEL / "variance_decomposition.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    single = sorted(rows[:-1], key=lambda r: -r["mean_cv_top30"])
    md = ["# Variance decomposition", "",
          "Auto-generated by `scripts/variance_decomposition.py`. One noise source at a time on the top-30 baseline pairs; "
          "the noise magnitudes are those in `config/mc_noise.yaml` (derived from data except the per-sport multiplier), so this ranks layers by influence "
          "*under the model's current structure*, not by measured error.", "",
          "| Layer perturbed | Mean relative spread of M (sd/mean) | P(baseline #1 stays #1) | Mean rank sd |", "|---|---|---|---|"]
    md += [f"| {r['component']} | {r['mean_cv_top30']:.3f} | {r['p_baseline_top1_stays_top1']:.2f} | {r['mean_rank_sd_top30']:.1f} |" for r in rows]
    md += ["", f"Largest single contributor: **{single[0]['component']}**, then {single[1]['component']}. "
           "Rivalry (S, T) and identity (E) are analyst priors, so a large share there means the ranking mostly reflects those judgments until milestone M3 replaces them with measurements."]
    (ROOT / "docs" / "VARIANCE_DECOMPOSITION.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 150)
