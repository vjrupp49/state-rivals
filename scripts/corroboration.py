"""Corroboration conditions and rivalry type for the leading pairs (design: docs/RIVALRY_WEIGHT_DESIGN.md, section 3 and 'Is one rivalry enough').

Thresholds, fixed before this table was computed (2026-10-16) but AFTER the state-level ranks of the lead pairs (IL-WI 28th, MA-NY 138th) were already known:
  C1 state-level framing: rank in the independent state-vs-state 'X sucks' searches within the top 5% of the pairs that were measured in both directions (rank <= 5% of the ranked pairs; about 33 of 677).
  C2 searches-only pair score: within the top 25% of the pairs scored by scripts/measured_hostility.py; 'not scored' is inconclusive, not a fail.
  C3 reciprocity: the weaker direction is at least 40% of the stronger (model H).
  Corroborated = C1 and C3 and (C2 passes or is inconclusive).
  Type: 'marquee-matchup' if either direction runs through about one matchup (effective number of channels < 1.5, measured where available,
        otherwise from the model); otherwise 'system'.
These conditions never change the score M (decision D-014 keeps the top-down view independent); they decide how a result may be described.

    python scripts/corroboration.py
"""
import csv
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from paths import ROOT  # noqa: E402

MODEL = ROOT / "data" / "model"


def rd(name):
    with open(MODEL / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def main(top_n=12):
    ps = rd("pair_scores.csv")[:top_n]
    td = {(r["state_a"], r["state_b"]): int(r["topdown_rank"]) for r in rd("topdown_pairs.csv")}
    meas = {r["pair"]: r for r in rd("measured_hostility.csv")}
    n_scored = len(meas)
    n_ranked = sum(1 for v_ in td.values() if v_ > 0)
    c1_cut = max(1, int(0.05 * n_ranked))        # top 5% of the pairs measured in both directions (NOT of all 1,225)
    rows = []
    for p in ps:
        a, b = p["state_a"], p["state_b"]
        key = f"{a}-{b}"
        tdr = td.get((a, b), td.get((b, a)))
        hab, hba = float(p["H_a_to_b"]), float(p["H_b_to_a"])
        recip = min(hab, hba) / max(hab, hba) if max(hab, hba) else 0
        m = meas.get(key)
        mr = int(m["measured_rank"]) if m else None
        c1 = tdr is not None and 0 < tdr <= c1_cut          # 0 / None = not measured in both directions: cannot corroborate
        c2 = None if mr is None else mr <= max(1, round(0.25 * n_scored))
        c3 = recip >= 0.4
        ne = []
        if m:
            ne = [float(m["neff_measured_a_to_b"]), float(m["neff_measured_b_to_a"])]
        corroborated = c1 and c3 and (c2 is None or c2)
        typ = "marquee-matchup" if ne and min(ne) < 1.5 else ("system" if ne else "n/a (not scored)")
        rows.append({"pair": key, "model_rank": int(p["rank"]), "topdown_rank": tdr, "C1_state_framing": c1,
                     "measured_rank": mr if mr else "", "C2_searches_only": "inconclusive" if c2 is None else c2,
                     "reciprocity": round(recip, 2), "C3_reciprocal": c3, "corroborated": corroborated, "type": typ,
                     "neff_ab": ne[0] if ne else "", "neff_ba": ne[1] if ne else ""})
    with open(MODEL / "corroboration.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator=chr(10))
        w.writeheader()
        w.writerows(rows)
    md = ["# Corroboration and type of the leading pairs", "",
          "Generated by `scripts/corroboration.py`. For each leading pair I ask whether evidence that does not depend on my team-level model points the same way. "
          "I fixed the three thresholds before computing this table, but after I had already seen the state-level ranks of the lead pairs (a disclosed limitation, see `docs/LIMITATIONS.md`).", "",
          f"- **C1, state-level framing:** people search against the state itself. The pair ranks within the top 5% of the {n_ranked} pairs measured in both directions (rank {c1_cut} or better).",
          f"- **C2, searches-only score:** a pair score built only from antipathy searches (no tiers, no attention weights) ranks the pair within the top 25% of the {n_scored} pairs where it can be computed. Pairs that cannot be scored are inconclusive, not failures.",
          "- **C3, reciprocity:** the smaller of the two directed hostilities is at least 40% of the larger (ratio 0.4 or more).",
          "- **Type:** *marquee-matchup* if the effective number of channels (N_eff) is below 1.5 in either direction, otherwise *system*.", "",
          "These conditions describe a result. They never change a score.", "",
          "| Model rank | Pair | State-level rank (C1) | Searches-only rank of scored (C2) | Reciprocity (C3) | Corroborated | Type | N_eff a to b / b to a |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        yn = lambda x: "pass" if x is True else ("fail" if x is False else str(x))
        md.append(f"| {r['model_rank']} | {r['pair']} | {r['topdown_rank']} ({yn(r['C1_state_framing'])}) | {r['measured_rank'] or 'not scored'} ({yn(r['C2_searches_only'])}) | {r['reciprocity']} ({yn(r['C3_reciprocal'])}) | **{'yes' if r['corroborated'] else 'no'}** | {r['type']} | {r['neff_ab'] or '-'} / {r['neff_ba'] or '-'} |")
    (ROOT / "docs/CORROBORATION.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8", newline=chr(10))
    print(chr(10).join(md[5:]))


if __name__ == "__main__":
    main()
