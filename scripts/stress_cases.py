"""Decompose the three methodological stress cases (docs/PROTOCOL.md section 7) into their top channels.

Writes docs/STRESS_CASES.md. Channel = source state -> supported entity -> rival entity -> embodied state.
Rebuilt from data/model matrices; re-run after any model rebuild:  python scripts/stress_cases.py
"""
import pathlib
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import lib_model as LM  # noqa: E402

ROOT = LM.ROOT
CASES = [("KS", "MO", "Shared fandom and metro ambiguity: KU-Mizzou, Chiefs, Sporting KC"),
         ("MA", "NY", "Multi-market state: Yankees-Red Sox, Patriots-Jets/Bills, Celtics-Knicks"),
         ("OR", "WA", "Cross-sport reinforcement: football, MLS, NWSL, WNBA")]


def channels(src, dst, states, ids, A, R, E, buckets, F, k=6):
    s, d = states.index(src), buckets.index(dst)
    contrib = A[s][:, None] * R * E[:, d][None, :] * F[s][None, :]        # (entity i, entity j), with the place factor
    flat = np.dstack(np.unravel_index(np.argsort(-contrib, axis=None)[:k], contrib.shape))[0]
    total = contrib.sum()
    rows = [(ids[i], ids[j], contrib[i, j], contrib[i, j] / total) for i, j in flat if contrib[i, j] > 0]
    return total, rows


def main():
    states, ids, A, other = LM.load_A()
    reg = {e["entity_id"]: e for e in LM.load_entities()}
    ents = [reg[e] for e in ids]
    R = LM.build_R(ids, [e for e in LM.build_edges() if e[0] != "UNRESOLVED"])
    E, buckets = LM.build_E(ents, states)
    F = LM.place_matrix(states, ids, ents)
    ps = pd.read_csv(ROOT / "data/model/pair_scores.csv").set_index(["state_a", "state_b"])
    out = ["# Stress cases", "",
           "Auto-generated by `scripts/stress_cases.py` from the current model. Channel contributions are shares of the directed score. "
           "The rivalry (S, T) and identity (E) inputs are my priors, tested against measured searches where the data allow (see `docs/LIMITATIONS.md`). The ranks are model outputs, not measurements.", ""]
    for a, b, why in CASES:
        r = ps.loc[(a, b)]
        out += [f"## {a}-{b}: {why}", "",
                f"Rank **{int(r['rank'])}** of 1,225, M = {r.M:.4f}; H({a}->{b}) = {r.H_a_to_b:.4f}, H({b}->{a}) = {r.H_b_to_a:.4f}, reciprocity {r.reciprocity_ratio:.2f}.", ""]
        for src, dst in ((a, b), (b, a)):
            tot, rows = channels(src, dst, states, ids, A, R, E, buckets, F)
            out += [f"**{src} residents -> {dst} identity** (total {tot:.4f})", "", "| Supported entity | Rival entity | Contribution | Share |", "|---|---|---|---|"]
            out += [f"| {x} | {y} | {c:.5f} | {s:.0%} |" for x, y, c, s in rows]
            out.append("")
    (ROOT / "docs" / "STRESS_CASES.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("wrote docs/STRESS_CASES.md")


if __name__ == "__main__":
    main()
