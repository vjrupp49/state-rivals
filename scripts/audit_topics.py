"""Audit Google Trends topic resolution (M2) and refresh data/raw/google_topics.csv from the live cache.

For every entity that has been resolved, records the Trends topic id, the title Google returned and whether a
plain-term fallback is used. Flags suspicious matches: the topic title shares no word with the entity's
school or team name, which usually means the wrong topic. Writes a short audit to docs/TOPIC_AUDIT.md.

    python scripts/audit_topics.py
"""
import csv
import collections
import pathlib
import re
import sqlite3
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from paths import ROOT, WORK  # noqa: E402

OUT = ROOT / "data" / "raw" / "google_topics.csv"
DOC = ROOT / "docs" / "TOPIC_AUDIT.md"
STOP = {"the", "of", "university", "college", "state", "men's", "women's", "football", "basketball", "baseball", "softball",
        "hockey", "ice", "lacrosse", "volleyball", "wrestling", "team", "and", "at", "a", "m"}


def toks(s):
    return {t for t in re.findall(r"[a-z0-9&]+", s.lower()) if t not in STOP and len(t) > 1}


def fam(eid):
    p = eid.split("_")
    return "_".join(p[:2]) if p[0] in ("cbb", "hky", "lax") else p[0]


def main():
    con = sqlite3.connect(WORK / "trends.sqlite", timeout=60)
    sugg = {r[0]: r[1:] for r in con.execute("SELECT entity_id,query,mid,title,type,status FROM sugg")}
    con.close()
    ents = list(csv.DictReader(open(ROOT / "data" / "registries" / "entities.csv", encoding="utf-8")))
    rows, stats, flagged = [], collections.defaultdict(collections.Counter), []
    for e in ents:
        eid = e["entity_id"]
        f = fam(eid)
        s = sugg.get(eid)
        if not s:
            status, mid, title, ty, query = "unresolved", "", "", "", e["entity_name"]
        else:
            query, mid, title, ty, status = s
        suspicious = ""
        if status == "topic" and not (toks(e["entity_name"]) & toks(title)):
            suspicious = "title shares no name token"
            flagged.append((eid, e["entity_name"], title))
        stats[f][status + ("_suspicious" if suspicious else "")] += 1
        rows.append({"entity_id": eid, "entity_name": e["entity_name"], "query_string": query, "query_type": ty or "term",
                     "trends_topic_mid": mid, "topic_title": title, "status": status, "ambiguity_flag": "yes" if suspicious else "no",
                     "ambiguity_reason": suspicious, "retrieved_at": "see Trends cache"})
    with open(OUT, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    lines = ["# Topic resolution audit", "",
             "Auto-generated by `scripts/audit_topics.py`. A *topic* is a Google Trends entity id (unambiguous); a *term_fallback* is a plain search string "
             "(ambiguous for names like Heat or Giants); *unresolved* entities have no topic id and are queried by their plain name, which is less precise (this applies to most college programs outside football). *Suspicious* means the returned topic title shares "
             "no name word with the entity: review before trusting.", "",
             "| Family | topic | suspicious | term_fallback | unresolved |", "|---|---|---|---|---|"]
    for f, c in sorted(stats.items()):
        lines.append(f"| {f} | {c['topic']} | {c['topic_suspicious']} | {c['term_fallback']} | {c['unresolved']} |")
    lines += ["", "## Suspicious matches (first 40)", ""] + [f"- `{e}`: {n} -> *{t}*" for e, n, t in flagged[:40]]
    DOC.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    tot = collections.Counter()
    for c in stats.values():
        tot.update(c)
    print(dict(tot))


if __name__ == "__main__":
    main()
