"""Derive Monte Carlo noise magnitudes from data (open item 1 in output/verdict.json).

1. Rivalry/identity layer (S, T, E). From the gravity fit (data/model/gravity_distance.csv): after removing state and team effects, the tier ladder
   and distance, the log residual of measured antipathy has a standard deviation of resid_sd; subtracting the Trends measurement variance leaves
   model_error_sd per state-team cell. A cell sums several rival channels, so the per-edge error is larger by about sqrt(n_eff), where n_eff is the
   effective number of rival channels feeding the cell (computed from the model). The composite per-edge sd replaces the analyst values for S, T and E
   by rescaling them in their original proportions.
2. Sport mix (W). The year-to-year spread of each sport's state-level search level (last 12 months versus the year before; includes real change, so it is
   a conservative width).
3. Not derivable from team-level data: per-sport systematic multipliers (a team fixed effect absorbs any sport-wide scale). Kept at the analyst value 0.30 and flagged.
4. Team attention A: per-cell log standard deviations already come from the Trends estimator (A_meta.csv); unchanged.

Writes config/mc_noise.yaml (read by scripts/robustness.py) and docs/NOISE_DERIVATION.md.

    python scripts/derive_noise.py
"""
import csv
import math
import pathlib
import sys

import numpy as np

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import lib_model as LM  # noqa: E402
import lib_trends as L  # noqa: E402
import trends_worker as TW  # noqa: E402

ROOT = LM.ROOT
ANALYST = {"s_edge_sd": 0.35, "t_sd": 0.25, "e_sd": 0.15, "w_mix_sd": 0.20, "sport_mult_sd": 0.30}


def main():
    states, ids, A, _ = LM.load_A()
    eidx = {e: k for k, e in enumerate(ids)}
    edges = [e for e in LM.build_edges() if e[0] != "UNRESOLVED"]
    R = LM.build_R(ids, edges)
    gd = {r["league"]: r for r in csv.DictReader(open(ROOT / "data/model/gravity_distance.csv", encoding="utf-8"))}
    reg = {e["entity_id"]: e for e in LM.load_entities()}
    per = []
    detail = []
    for lg in ("nfl", "mlb", "nba"):
        if lg not in gd:
            continue
        teams = [t for t in TW._hate_terms(lg) if t in eidx]
        ne = []
        for t in teams:
            col = R[:, eidx[t]]
            for s in range(len(states)):
                w = A[s] * col
                tot = w.sum()
                if tot > 0:
                    ne.append(tot ** 2 / np.sum(w ** 2))
        n_eff = float(np.mean(ne))
        sd_cell = float(gd[lg]["model_error_sd_log"])
        per.append(sd_cell * math.sqrt(n_eff))
        detail.append((lg, float(gd[lg]["resid_sd_log"]), float(gd[lg]["meas_sd_log"]), sd_cell, n_eff, sd_cell * math.sqrt(n_eff)))
    edge_sd = float(np.mean(per))
    comp = math.sqrt(ANALYST["s_edge_sd"] ** 2 + ANALYST["t_sd"] ** 2 + ANALYST["e_sd"] ** 2)
    k = edge_sd / comp
    # sport mix: year-to-year spread of sport-level search interest
    smap = L.state_map()
    jobs = L.load_jobs(family="SPORT")
    est = L.estimate(jobs, smap)
    diffs = []
    for (name, sid, win), (ln, var, flag) in est.items():
        if win == "W0" and flag == "ok":
            e1 = est.get((name, sid, "W1"))
            if e1 and e1[2] == "ok":
                diffs.append(ln - e1[0])
    w_sd = float(np.std(diffs)) if len(diffs) > 30 else ANALYST["w_mix_sd"]
    gsd = float(np.mean([(float(gd[lg]["gamma_hi"]) - float(gd[lg]["gamma_lo"])) / 3.29 for lg in ("nfl", "mlb") if lg in gd] or [0.06]))
    cfg = {"gamma_sd": round(gsd, 3), "s_edge_sd": round(ANALYST["s_edge_sd"] * k, 3), "t_sd": round(ANALYST["t_sd"] * k, 3), "e_sd": round(ANALYST["e_sd"] * k, 3),
           "w_mix_sd": round(min(w_sd, 0.6), 3), "sport_mult_sd": ANALYST["sport_mult_sd"]}
    text = ("# Monte Carlo noise magnitudes (log-normal sd). Derived from data by scripts/derive_noise.py; see docs/NOISE_DERIVATION.md.\n"
            "# sport_mult_sd is NOT derivable from team-level data and stays at the analyst value.\n"
            f"s_edge_sd: {cfg['s_edge_sd']}\nt_sd: {cfg['t_sd']}\ne_sd: {cfg['e_sd']}\nw_mix_sd: {cfg['w_mix_sd']}\nsport_mult_sd: {cfg['sport_mult_sd']}\n")
    text += "gamma_sd: " + str(cfg["gamma_sd"]) + chr(10)      # uncertainty of the place-factor gamma (bootstrap interval of the NFL and MLB fits)
    (ROOT / "config" / "mc_noise.yaml").write_text(text, encoding="utf-8", newline="\n")
    md = ["# Where the simulation noise comes from", "",
          "Auto-generated by `scripts/derive_noise.py`. The Monte Carlo noise levels are derived from how far the model misses the measured antipathy, not chosen by hand; `config/mc_noise.yaml` holds the result. The one exception is the per-sport systematic multiplier, which team-level data cannot identify and which I set myself (sd 0.30).", "",
          "| League | Residual sd (log) | Trends measurement sd | Model error sd per state-team cell | Effective rival channels per cell | Per-edge sd |", "|---|---|---|---|---|---|"]
    for lg, r, m, sc, ne_, pe in detail:
        md.append(f"| {lg} | {r:.2f} | {m:.2f} | {sc:.2f} | {ne_:.1f} | {pe:.2f} |")
    md += ["", f"Mean per-edge sd (S, T and E combined): **{edge_sd:.2f}**, against the analyst composite {comp:.2f} (a factor of {k:.2f}); S, T and E are rescaled in their original proportions to "
           f"{cfg['s_edge_sd']}, {cfg['t_sd']} and {cfg['e_sd']}. Sport-mix sd from year-to-year variation of sport-level search: **{cfg['w_mix_sd']}** (analyst: {ANALYST['w_mix_sd']}). "
           f"Per-sport multiplier sd stays {cfg['sport_mult_sd']} (not identifiable from team-level data).", "",
          "Caveats: the residual comes from an in-sample fit with team and state effects (so it understates true out-of-sample error); the n_eff scaling assumes independent edge errors; year-to-year variation includes real change."]
    (ROOT / "docs/NOISE_DERIVATION.md").write_text(chr(10).join(md) + chr(10), encoding="utf-8", newline=chr(10))
    print(chr(10).join(md[4:12]))


if __name__ == "__main__":
    main()
